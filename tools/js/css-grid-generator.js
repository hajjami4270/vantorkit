      // Gradient Studio Implementation
      function renderGradientStudio() {
        const stopsStr = colorStops.map(s => s.color + ' ' + s.pos + '%').join(', ');
        let cssValue = '';

        if (gradType === 'linear') {
          gradAngleGroup.style.display = 'flex';
          cssValue = 'linear-gradient(' + gradAngle + 'deg, ' + stopsStr + ')';
        } else if (gradType === 'radial') {
          gradAngleGroup.style.display = 'none';
          cssValue = 'radial-gradient(circle at center, ' + stopsStr + ')';
        } else if (gradType === 'conic') {
          gradAngleGroup.style.display = 'flex';
          cssValue = 'conic-gradient(from ' + gradAngle + 'deg at 50% 50%, ' + stopsStr + ')';
        }

        gradientPreviewBox.style.background = cssValue;

        const fullCSS = '/* CSS Gradient Output */\n.gradient-element {\n  background: ' + colorStops[0].color + ';\n  background: ' + cssValue + ';\n}';
        gradientCodeView.textContent = fullCSS;

        renderGradientStopsList();
      }

      function renderGradientStopsList() {
        gradientStopsList.innerHTML = '';
        colorStops.forEach((stop, idx) => {
          const row = document.createElement('div');
          row.className = 'stop-row';

          const picker = document.createElement('input');
          picker.type = 'color';
          picker.className = 'color-picker-input';
          picker.value = stop.color;
          picker.addEventListener('input', (e) => {
            stop.color = e.target.value;
            renderGradientStudio();
          });

          const slider = document.createElement('input');
          slider.type = 'range';
          slider.className = 'slider-range';
          slider.min = '0';
          slider.max = '100';
          slider.value = stop.pos;
          slider.addEventListener('input', (e) => {
            stop.pos = Number(e.target.value);
            renderGradientStudio();
          });

          const posLabel = document.createElement('span');
          posLabel.style.fontSize = '0.8rem';
          posLabel.style.fontFamily = 'var(--font-code)';
          posLabel.style.color = '#c084fc';
          posLabel.style.width = '42px';
          posLabel.textContent = stop.pos + '%';

          const btnDel = document.createElement('button');
          btnDel.type = 'button';
          btnDel.className = 'num-btn';
          btnDel.textContent = '✕';
          btnDel.title = 'Remove Stop';
          btnDel.addEventListener('click', () => {
            if (colorStops.length > 2) {
              colorStops.splice(idx, 1);
              renderGradientStudio();
            } else {
              showToast('At least 2 color stops are required!');
            }
          });

          row.appendChild(picker);
          row.appendChild(slider);
          row.appendChild(posLabel);
          row.appendChild(btnDel);
          gradientStopsList.appendChild(row);
        });
      }

      selectGradType.addEventListener('change', (e) => {
        gradType = e.target.value;
        renderGradientStudio();
      });

      sliderGradAngle.addEventListener('input', (e) => {
        gradAngle = Number(e.target.value);
        valGradAngle.textContent = gradAngle + '°';
        renderGradientStudio();
      });

